#Problema: Faça um programa que receba quatro números inteiros, calcule e mostre a soma desses números.

valor_01 = float(input("Digite o primeiro valor >> "))
valor_02 = float(input("Digite o segundo valor >> "))
valor_03 = float(input("Digite o terceiro valor >> "))
valor_04 = float(input("Digite o quarto valor >> "))
soma = valor_01 + valor_02 + valor_03 + valor_04
print("A soma dos 4 valores é >> {}".format(soma))
